def exec_human_approval(node: AgentNode, spec: AgentSpecification, variables: dict) -> dict:
    """
    Pauses the graph and surfaces exactly what's being asked, matching the
    approval-card shape in architecture doc section 13. Resumed with
    Command(resume={"approved": bool, "reason": str | None}).
    """
    decision = interrupt(
        {
            "type": "human_approval",
            "node_id": node.id,
            "label": node.label,
            "action_category": node.config.get("actionCategory"),
            # Surface the relevant variables so the approver sees what
            # they're approving (e.g. amount, recipient) without needing
            # to inspect the raw graph.
            "context": {k: v for k, v in variables.items() if k in node.config.get("show_variables", list(variables.keys()))},
        }
    )
    approved = bool(decision.get("approved", False)) if isinstance(decision, dict) else bool(decision)
    result = {"approved": approved}
    if isinstance(decision, dict) and decision.get("reason"):
        result["approval_reason"] = decision["reason"]
    return result


