def exec_preview(node: AgentNode, spec: AgentSpecification, variables: dict) -> dict:
    """Collect text for the UI Preview node; does not write to disk."""
    import json
    key = (
        (node.config or {}).get("source")
        or (node.config or {}).get("content_variable")
        or "ai_response"
    )
    content = variables.get(key)
    if content is None or content == "":
        for fallback in ("ai_response", "draft_email", "summary", "rag_context", "email"):
            content = variables.get(fallback)
            if content is not None and content != "":
                break
    if content is None:
        content = ""
    if not isinstance(content, str):
        try:
            content = json.dumps(content, indent=2, default=str)
        except Exception:
            content = str(content)
    title = (node.config or {}).get("title") or node.label or "Preview"
    return {
        "preview_content": content,
        "preview_markdown": content,
        "preview_title": title,
        "preview_source": key,
    }


