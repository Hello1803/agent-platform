# Max wait duration for `wait` nodes (see exec_wait below) — a
# misconfigured spec (or a typo'd seconds value several orders of
# magnitude too large) shouldn't be able to hang a run indefinitely; a
# real deployment wanting longer delays should use a schedule/trigger
# instead of a single in-run wait.
MAX_WAIT_SECONDS = 300


def exec_wait(node: AgentNode, spec: AgentSpecification, variables: dict) -> dict:
    """Real delay — genuinely calls time.sleep(), not a no-op. `wait` was
    exec_passthrough before this (config.seconds silently ignored, the
    node just... didn't wait). node.config.seconds may reference a
    variable by name (e.g. "retry_after") the same way api_call's body
    fields do — falls back to a literal number otherwise."""
    seconds = node.config.get("seconds", 0)
    if isinstance(seconds, str):
        seconds = variables.get(seconds, 0)
    try:
        seconds = float(seconds)
    except (TypeError, ValueError):
        seconds = 0.0
    seconds = max(0.0, min(seconds, MAX_WAIT_SECONDS))
    if seconds > 0:
        time.sleep(seconds)
    return {}



def _parse_loop_items(raw, items_path: str | None):
    """Turn a variable value into a list of items for for-each iteration."""
    import json
    if raw is None:
        return []
    if isinstance(raw, list):
        items = raw
    elif isinstance(raw, dict):
        if items_path and items_path in raw:
            items = raw[items_path]
        elif "filtered_students" in raw:
            items = raw["filtered_students"]
        elif "items" in raw:
            items = raw["items"]
        else:
            items = [raw]
    elif isinstance(raw, str):
        text = raw.strip()
        # Pull a JSON object/array out of prose (Ask AI often wraps JSON in markdown).
        start_obj, start_arr = text.find("{"), text.find("[")
        starts = [s for s in (start_obj, start_arr) if s >= 0]
        if starts:
            start = min(starts)
            try:
                parsed = json.loads(text[start:])
            except json.JSONDecodeError:
                # try fenced block
                if "```" in text:
                    chunk = text.split("```", 2)[1]
                    if chunk.startswith("json"):
                        chunk = chunk[4:]
                    parsed = json.loads(chunk.strip())
                else:
                    raise
            return _parse_loop_items(parsed, items_path)
        return []
    else:
        return []
    if not isinstance(items, list):
        return []
    return items


def exec_loop(node: AgentNode, spec: AgentSpecification, variables: dict) -> dict:
    """For-each over a list variable.

    Config:
      items_variable: name of the variable holding the list or JSON (default "ai_response")
      items_path: optional key inside a parsed JSON object (e.g. "filtered_students")
      item_variable: name to expose the current element under (default "current_item")
      email_field: field on each item used to set variables["to"] (default "Email")
      index_variable: loop index variable (default "_loop_index")

    Edge conditions (from the loop node):
      continue into body:  _loop_continue == true
      exit when done:      _loop_continue == false   (or an unconditional edge after the body path)
    """
    items_var = node.config.get("items_variable") or node.config.get("itemsVariable") or "ai_response"
    items_path = node.config.get("items_path") or node.config.get("itemsPath")
    item_var = node.config.get("item_variable") or node.config.get("itemVariable") or "current_item"
    index_var = node.config.get("index_variable") or node.config.get("indexVariable") or "_loop_index"
    email_field = node.config.get("email_field") or node.config.get("emailField") or "Email"

    raw = variables.get(items_var)
    try:
        items = _parse_loop_items(raw, items_path)
    except Exception as exc:
        raise RuntimeError(f"Loop '{node.id}' could not parse items from '{items_var}': {exc}") from exc

    index = int(variables.get(index_var) or 0)
    if index >= len(items):
        return {
            index_var: index,
            "_loop_continue": False,
            "_loop_done": True,
            "_loop_total": len(items),
        }

    item = items[index]
    updates = {
        item_var: item,
        index_var: index + 1,  # advance for next visit
        "_loop_continue": True,
        "_loop_done": False,
        "_loop_total": len(items),
        "_loop_remaining": len(items) - index - 1,
    }
    if isinstance(item, dict):
        for key in (email_field, "Email", "email", "EMAIL"):
            if item.get(key):
                updates["to"] = str(item[key])
                updates["recipient_email"] = str(item[key])
                break
        # Convenience flat fields for templates
        for k, v in item.items():
            if isinstance(v, (str, int, float, bool)) or v is None:
                updates[f"item_{k}"] = v
    return updates


