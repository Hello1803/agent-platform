"""
Node executors: one function per NodeType, dispatched by the compiler.

For this MVP these are STUBS — they don't call a real LLM or a real Gmail/
Sheets API. Each stub is written to the exact interface a real
implementation would use, so swapping a stub for `openai/anthropic call
here` or `actual Gmail API call here` later doesn't touch the compiler or
the graph-building logic at all. That boundary is the point: the compiler
turns a spec into a graph shape; executors are what actually do work at
each node, and are the natural plug-in point for real model/tool calls.

Every executor has the signature:
    (node: AgentNode, spec: AgentSpecification, variables: dict) -> dict
returning ONLY the variables it wants to add/update in state — never the
whole state (LangGraph reducers merge it in, see state.py).
"""

from __future__ import annotations

import time
from typing import Any, Callable

from langgraph.types import interrupt

from backend.models.agent_spec import AgentNode, AgentSpecification, NodeType

NodeExecutor = Callable[[AgentNode, AgentSpecification, dict[str, Any]], dict[str, Any]]


class ToolPermissionError(PermissionError):
    """Raised when a node tries to use a tool binding it wasn't granted."""


def _require_tool(node: AgentNode, spec: AgentSpecification, capability: str):
    """
    Defense-in-depth: the compiler already checks this at compile time
    (see compiler.py:_check_tool_permissions), but executors re-check at
    call time too, since a real deployment may hot-swap credentials or
    revoke a scope between compile and run.
    """
    if not node.tool_refs:
        raise ToolPermissionError(f"Node '{node.id}' has no tool binding but tried to use one.")
    bindings = {t.id for t in spec.tools if capability in t.permissions}
    if not any(ref in bindings for ref in node.tool_refs):
        raise ToolPermissionError(
            f"Node '{node.id}' is not permitted capability '{capability}' "
            f"(tool_refs={node.tool_refs})."
        )


